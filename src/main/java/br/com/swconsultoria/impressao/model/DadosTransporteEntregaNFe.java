package br.com.swconsultoria.impressao.model;

public class DadosTransporteEntregaNFe {

    private String transportadoraNome;
    private String entregaNome;
    private String entregaDocumento;
    private String entregaEndereco;
    private String entregaMunicipio;
    private String entregaUf;

    public String getTransportadoraNome() {
        return transportadoraNome;
    }

    public void setTransportadoraNome(String transportadoraNome) {
        this.transportadoraNome = transportadoraNome;
    }

    public String getEntregaNome() {
        return entregaNome;
    }

    public void setEntregaNome(String entregaNome) {
        this.entregaNome = entregaNome;
    }

    public String getEntregaDocumento() {
        return entregaDocumento;
    }

    public void setEntregaDocumento(String entregaDocumento) {
        this.entregaDocumento = entregaDocumento;
    }

    public String getEntregaEndereco() {
        return entregaEndereco;
    }

    public void setEntregaEndereco(String entregaEndereco) {
        this.entregaEndereco = entregaEndereco;
    }

    public String getEntregaMunicipio() {
        return entregaMunicipio;
    }

    public void setEntregaMunicipio(String entregaMunicipio) {
        this.entregaMunicipio = entregaMunicipio;
    }

    public String getEntregaUf() {
        return entregaUf;
    }

    public void setEntregaUf(String entregaUf) {
        this.entregaUf = entregaUf;
    }
}
